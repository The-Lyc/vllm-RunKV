def profile_gpu_peak_flops(
    device: torch.device,
    dtype: torch.dtype = torch.float16,
) -> float:
    """Benchmark GPU peak FLOPS by scanning several matmul shapes.

    A single fixed shape (e.g. 4096³) frequently underestimates peak —
    cuBLAS picks different kernels for different shapes, and some
    workload-relevant shapes (rectangular FFN GEMMs, FP16-accumulate
    paths used by FlashAttention) routinely beat a square 4096³
    measurement.  We scan several square + rectangular shapes and
    return the maximum achieved FLOPS.
    """
    shapes: list[tuple[int, int, int]] = [
        (2048, 2048, 2048),
        (4096, 4096, 4096),
        (8192, 8192, 8192),
        (4096, 8192, 4096),
        (8192, 4096, 8192),
        (2048, 8192, 2048),
    ]

    best = 0.0
    for M, N, K in shapes:
        try:
            a = torch.randn(M, K, device=device, dtype=dtype)
            b = torch.randn(K, N, device=device, dtype=dtype)

            for _ in range(10):
                torch.mm(a, b)
            torch.cuda.synchronize()

            iters = 50
            start = torch.cuda.Event(enable_timing=True)
            end = torch.cuda.Event(enable_timing=True)
            start.record()
            for _ in range(iters):
                torch.mm(a, b)
            end.record()
            torch.cuda.synchronize()

            elapsed_s = start.elapsed_time(end) / 1000.0
            flops = 2 * M * N * K * iters / elapsed_s
            if flops > best:
                best = flops

            del a, b
            torch.cuda.empty_cache()
        except torch.cuda.OutOfMemoryError:
            torch.cuda.empty_cache()
            continue

    return best


def profile_pcie_bandwidth(
    device: torch.device,
    block_size: int = 16,
    num_kv_heads: int = 32,
    head_dim: int = 80,
    dtype: torch.dtype = torch.float16,
    num_blocks_list: list[int] | None = None,
) -> float:
    """Profile effective PCIe H2D bandwidth via pinned-memory copies."""
    if num_blocks_list is None:
        num_blocks_list = [16, 32, 64, 128, 256, 512]

    dtype_bytes = torch.tensor([], dtype=dtype).element_size()
    bandwidths: list[float] = []

    for num_blocks in num_blocks_list:
        total_elements = num_blocks * block_size * 2 * num_kv_heads * head_dim
        total_bytes = total_elements * dtype_bytes

        cpu_tensor = torch.randn(total_elements, dtype=dtype).pin_memory()
        gpu_tensor = torch.empty(total_elements, device=device, dtype=dtype)

        # Warmup
        for _ in range(5):
            gpu_tensor.copy_(cpu_tensor, non_blocking=True)
            torch.cuda.synchronize()

        iters = 20
        start = torch.cuda.Event(enable_timing=True)
        end = torch.cuda.Event(enable_timing=True)
        start.record()
        for _ in range(iters):
            gpu_tensor.copy_(cpu_tensor, non_blocking=True)
        end.record()
        torch.cuda.synchronize()

        elapsed_s = start.elapsed_time(end) / 1000.0
        bw = (total_bytes * iters) / elapsed_s
        bandwidths.append(bw)

    # Return median bandwidth
    return float(sorted(bandwidths)[len(bandwidths) // 2])


def _run_attention_microbenchmark(
    x: torch.Tensor,
    w_qkv: torch.Tensor,
    w_out: torch.Tensor,
    *,
    model_type: str,
    num_heads: int,
    num_kv_heads: int,
    head_dim: int,
    norm_weight: torch.Tensor | None = None,
    norm_eps: float = 1e-5,
) -> torch.Tensor:
    """Execute one architecture-faithful attention microbenchmark."""

    if model_type == "llama":
        if norm_weight is None:
            raise ValueError("Llama attention profiling requires RMSNorm weights.")
        x = F.rms_norm(x, (x.shape[-1],), norm_weight, norm_eps)
    elif model_type != "opt":
        raise ValueError(f"Unsupported model_type={model_type!r}.")

    batch_size, seq_len, _ = x.shape
    q_size = num_heads * head_dim
    kv_size = num_kv_heads * head_dim
    qkv = torch.matmul(x, w_qkv)
    q_part, k_part, v_part = qkv.split([q_size, kv_size, kv_size], dim=-1)
    q = q_part.view(batch_size, seq_len, num_heads, head_dim).transpose(1, 2)
    k = k_part.view(batch_size, seq_len, num_kv_heads, head_dim).transpose(1, 2)
    v = v_part.view(batch_size, seq_len, num_kv_heads, head_dim).transpose(1, 2)

    # Full L² attention (no causal mask) keeps executed work consistent with
    # the FLOP formula used for the MFU denominator.
    attn_out = F.scaled_dot_product_attention(
        q,
        k,
        v,
        enable_gqa=num_kv_heads != num_heads,
    )
    attn_out = (
        attn_out.transpose(1, 2)
        .contiguous()
        .view(batch_size, seq_len, q_size)
    )
    return torch.matmul(attn_out, w_out)


def _run_mlp_microbenchmark(
    x: torch.Tensor,
    w_in: torch.Tensor,
    w_out: torch.Tensor,
    *,
    model_type: str,
    norm_weight: torch.Tensor | None = None,
    norm_eps: float = 1e-5,
) -> torch.Tensor:
    """Execute one OPT-ReLU or Llama-RMSNorm/SwiGLU MLP benchmark."""

    if model_type == "llama":
        if norm_weight is None:
            raise ValueError("Llama MLP profiling requires RMSNorm weights.")
        x = F.rms_norm(x, (x.shape[-1],), norm_weight, norm_eps)
        gate, up = torch.matmul(x, w_in).chunk(2, dim=-1)
        hidden = F.silu(gate) * up
    elif model_type == "opt":
        hidden = F.relu(torch.matmul(x, w_in))
    else:
        raise ValueError(f"Unsupported model_type={model_type!r}.")
    return torch.matmul(hidden, w_out)


def attention_flops_per_forward(
    *,
    seq_len: int,
    hidden_size: int,
    num_heads: int,
    head_dim: int,
    qkv_flops_coefficient: float,
    output_flops_coefficient: float,
    score_flops_coefficient: float = 4.0,
) -> float:
    """Model FLOPs for the profiled prefill attention forward."""

    projection_flops = (
        (qkv_flops_coefficient + output_flops_coefficient)
        * seq_len
        * hidden_size
        * hidden_size
    )
    score_flops = (
        score_flops_coefficient
        * num_heads
        * seq_len
        * seq_len
        * head_dim
    )
    return projection_flops + score_flops


def mlp_flops_per_forward(
    *,
    seq_len: int,
    hidden_size: int,
    ffn_dim: int,
    mlp_flops_coefficient: float,
) -> float:
    """Model FLOPs for the profiled OPT or Llama MLP forward."""

    return mlp_flops_coefficient * seq_len * hidden_size * ffn_dim


def profile_mfu_attn(
    device: torch.device,
    hidden_size: int,
    num_heads: int,
    head_dim: int,
    peak_flops: float,
    seq_lengths: list[int],
    dtype: torch.dtype = torch.float16,
    *,
    num_kv_heads: int | None = None,
    model_type: str = "opt",
    norm_eps: float = 1e-5,
    qkv_flops_coefficient: float | None = None,
    output_flops_coefficient: float = 2.0,
    score_flops_coefficient: float = 4.0,
) -> dict[int, float]:
    """Profile attention MFU at discrete sequence lengths.

    Matches TightLLM (Hu et al., IEEE TC 2025) §IV-B / Fig. 7: the curve
    is measured by running a *prefill* self-attention pass of length L
    (q.len = kv.len = L) and dividing the theoretical FLOPs by wall time.

    The default path is the legacy OPT MHA benchmark. The Llama path adds
    RMSNorm and uses configured Q/K/V widths (MHA for Llama-2-7B, GQA for
    variants with fewer KV heads).
    """
    if num_kv_heads is None:
        num_kv_heads = num_heads
    if num_heads % num_kv_heads != 0:
        raise ValueError("num_heads must be divisible by num_kv_heads")
    if model_type not in {"llama", "opt"}:
        raise ValueError(f"Unsupported model_type={model_type!r}.")
    if qkv_flops_coefficient is None:
        qkv_flops_coefficient = 2.0 + 4.0 * num_kv_heads / num_heads

    mfu_by_seqlen: dict[int, float] = {}

    for seq_len in seq_lengths:
        if seq_len <= 0:
            continue
        try:
            x = torch.randn(1, seq_len, hidden_size, device=device, dtype=dtype)
            q_size = num_heads * head_dim
            kv_size = num_kv_heads * head_dim
            w_qkv = torch.randn(
                hidden_size,
                q_size + 2 * kv_size,
                device=device,
                dtype=dtype,
            )
            w_out = torch.randn(q_size, hidden_size, device=device, dtype=dtype)
            norm_weight = (
                torch.ones(hidden_size, device=device, dtype=dtype)
                if model_type == "llama"
                else None
            )

            def _run():
                return _run_attention_microbenchmark(
                    x,
                    w_qkv,
                    w_out,
                    model_type=model_type,
                    num_heads=num_heads,
                    num_kv_heads=num_kv_heads,
                    head_dim=head_dim,
                    norm_weight=norm_weight,
                    norm_eps=norm_eps,
                )

            for _ in range(5):
                _run()
            torch.cuda.synchronize()

            iters = 50
            start = torch.cuda.Event(enable_timing=True)
            end = torch.cuda.Event(enable_timing=True)
            start.record()
            for _ in range(iters):
                _run()
            end.record()
            torch.cuda.synchronize()

            elapsed_s = start.elapsed_time(end) / 1000.0

            flops_per = attention_flops_per_forward(
                seq_len=seq_len,
                hidden_size=hidden_size,
                num_heads=num_heads,
                head_dim=head_dim,
                qkv_flops_coefficient=qkv_flops_coefficient,
                output_flops_coefficient=output_flops_coefficient,
                score_flops_coefficient=score_flops_coefficient,
            )
            actual = flops_per * iters / elapsed_s
            mfu_by_seqlen[seq_len] = actual / peak_flops

            del x, w_qkv, w_out, norm_weight
            torch.cuda.empty_cache()

        except torch.cuda.OutOfMemoryError:
            logger.warning(
                "OOM at seq_len=%d during attention profiling, skipping.", seq_len
            )
            torch.cuda.empty_cache()
            break

    return mfu_by_seqlen


def profile_mfu_ffn(
    device: torch.device,
    hidden_size: int,
    ffn_dim: int,
    peak_flops: float,
    seq_lengths: list[int],
    dtype: torch.dtype = torch.float16,
    *,
    model_type: str = "opt",
    norm_eps: float = 1e-5,
    mlp_flops_coefficient: float | None = None,
) -> dict[int, float]:
    """Profile FFN MFU at discrete sequence lengths (prefill-style).

    The legacy OPT path executes ReLU with input/output projections. Llama
    executes RMSNorm and SwiGLU with logical gate/up/down projections; gate
    and up share one packed GEMM, matching vLLM's merged projection.
    """
    if model_type not in {"llama", "opt"}:
        raise ValueError(f"Unsupported model_type={model_type!r}.")
    if mlp_flops_coefficient is None:
        mlp_flops_coefficient = 6.0 if model_type == "llama" else 4.0

    mfu_by_seqlen: dict[int, float] = {}

    for seq_len in seq_lengths:
        if seq_len <= 0:
            continue
        try:
            x = torch.randn(1, seq_len, hidden_size, device=device, dtype=dtype)
            input_projection_size = (
                2 * ffn_dim if model_type == "llama" else ffn_dim
            )
            w_in = torch.randn(
                hidden_size,
                input_projection_size,
                device=device,
                dtype=dtype,
            )
            w_out = torch.randn(ffn_dim, hidden_size, device=device, dtype=dtype)
            norm_weight = (
                torch.ones(hidden_size, device=device, dtype=dtype)
                if model_type == "llama"
                else None
            )

            def _run():
                return _run_mlp_microbenchmark(
                    x,
                    w_in,
                    w_out,
                    model_type=model_type,
                    norm_weight=norm_weight,
                    norm_eps=norm_eps,
                )

            for _ in range(5):
                _run()
            torch.cuda.synchronize()

            iters = 50
            start = torch.cuda.Event(enable_timing=True)
            end = torch.cuda.Event(enable_timing=True)
            start.record()
            for _ in range(iters):
                _run()
            end.record()
            torch.cuda.synchronize()

            elapsed_s = start.elapsed_time(end) / 1000.0
            flops_per = mlp_flops_per_forward(
                seq_len=seq_len,
                hidden_size=hidden_size,
                ffn_dim=ffn_dim,
                mlp_flops_coefficient=mlp_flops_coefficient,
            )
            actual = flops_per * iters / elapsed_s
            mfu_by_seqlen[seq_len] = actual / peak_flops

            del x, w_in, w_out, norm_weight
            torch.cuda.empty_cache()

        except torch.cuda.OutOfMemoryError:
            logger.warning(
                "OOM at seq_len=%d during FFN profiling, skipping.", seq_len
            )
            torch.cuda.empty_cache()
            break

    return mfu_by_seqlen


