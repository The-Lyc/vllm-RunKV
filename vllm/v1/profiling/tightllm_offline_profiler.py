# Profile data container
# ---------------------------------------------------------------------------


@dataclass
class TightLLMProfileData:
    """Offline profiled data for TightLLM ILP planner.

    Stores MFU look-up tables (keyed by effective sequence length),
    effective PCIe bandwidth, GPU peak FLOPS, and model architecture
    parameters needed for the analytical FLOPS model.
    """

    # MFU look-up tables: {effective_seq_len: mfu_ratio}
    mfu_attn_by_seqlen: dict[int, float] = field(default_factory=dict)
    mfu_ffn_by_seqlen: dict[int, float] = field(default_factory=dict)

    # PCIe H2D effective bandwidth (bytes/s)
    pcie_bandwidth_h2d: float = 0.0

    # GPU peak FLOPS (FP16/BF16 tensor-core throughput)
    gpu_peak_flops: float = 0.0

    # Model architecture constants
    hidden_size: int = 0
    num_attention_heads: int = 0
    num_kv_heads: int = 0
    head_dim: int = 0
    ffn_dim: int = 0  # intermediate_size / ffn_dim
    num_layers: int = 0
    dtype_bytes: int = 2  # FP16 / BF16
    model_type: str = "opt"

    # Architecture-aware analytical FLOP coefficients. Projection terms are:
    #
    #   attention QKV: coefficient * tokens * hidden_size**2
    #   attention out: coefficient * tokens * hidden_size**2
    #   MLP:           coefficient * tokens * hidden_size * ffn_dim
    #
    # Constructor defaults describe profiles generated by the current
    # profiler. ``load`` supplies the historical attention-score coefficient
    # (2) when reading legacy JSON that predates score·V accounting.
    attention_qkv_flops_coefficient: float = 6.0
    attention_output_flops_coefficient: float = 2.0
    attention_score_flops_coefficient: float = 4.0
    mlp_flops_coefficient: float = 4.0

    # Interpolation arrays (built from the dicts above)
    _mfu_attn_seqlens: np.ndarray = field(
        init=False, repr=False, default_factory=lambda: np.array([1.0])
    )
    _mfu_attn_values: np.ndarray = field(
        init=False, repr=False, default_factory=lambda: np.array([0.5])
    )
    _mfu_ffn_seqlens: np.ndarray = field(
        init=False, repr=False, default_factory=lambda: np.array([1.0])
    )
    _mfu_ffn_values: np.ndarray = field(
        init=False, repr=False, default_factory=lambda: np.array([0.5])
    )

    def __post_init__(self) -> None:
        self._build_interpolation_tables()

    def _build_interpolation_tables(self) -> None:
        for attr_dict, attr_sl, attr_val in (
            ("mfu_attn_by_seqlen", "_mfu_attn_seqlens", "_mfu_attn_values"),
            ("mfu_ffn_by_seqlen", "_mfu_ffn_seqlens", "_mfu_ffn_values"),
        ):
            d = getattr(self, attr_dict)
            if d:
                seqlens = sorted(d.keys())
                setattr(self, attr_sl, np.array(seqlens, dtype=np.float64))
                setattr(
                    self,
                    attr_val,
                    np.array([d[s] for s in seqlens], dtype=np.float64),
                )

    def lookup_mfu_attn(self, effective_seqlen: int) -> float:
        """Linearly interpolate MFU_attn for *effective_seqlen*."""
        return float(
            np.interp(effective_seqlen, self._mfu_attn_seqlens, self._mfu_attn_values)
        )

    def lookup_mfu_ffn(self, effective_seqlen: int) -> float:
        """Linearly interpolate MFU_ffn for *effective_seqlen*."""
        return float(
            np.interp(effective_seqlen, self._mfu_ffn_seqlens, self._mfu_ffn_values)
        )

    # ---- Serialisation ----

    def save(self, path: str | Path) -> None:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "mfu_attn_by_seqlen": {
                str(k): v for k, v in self.mfu_attn_by_seqlen.items()
            },
            "mfu_ffn_by_seqlen": {str(k): v for k, v in self.mfu_ffn_by_seqlen.items()},
            "pcie_bandwidth_h2d": self.pcie_bandwidth_h2d,
            "gpu_peak_flops": self.gpu_peak_flops,
            "hidden_size": self.hidden_size,
            "num_attention_heads": self.num_attention_heads,
            "num_kv_heads": self.num_kv_heads,
            "head_dim": self.head_dim,
            "ffn_dim": self.ffn_dim,
            "num_layers": self.num_layers,
            "dtype_bytes": self.dtype_bytes,
            "model_type": self.model_type,
            "attention_qkv_flops_coefficient": (
                self.attention_qkv_flops_coefficient
            ),
            "attention_output_flops_coefficient": (
                self.attention_output_flops_coefficient
            ),
            "attention_score_flops_coefficient": (
                self.attention_score_flops_coefficient
            ),
            "mlp_flops_coefficient": self.mlp_flops_coefficient,
        }
        with open(path, "w") as f:
            json.dump(data, f, indent=2)
        logger.info("TightLLM profile saved → %s", path)

    @classmethod
    def load(cls, path: str | Path) -> TightLLMProfileData:
        with open(path) as f:
            data = json.load(f)
        return cls(
            mfu_attn_by_seqlen={
                int(k): v for k, v in data["mfu_attn_by_seqlen"].items()
            },
            mfu_ffn_by_seqlen={int(k): v for k, v in data["mfu_ffn_by_seqlen"].items()},
            pcie_bandwidth_h2d=data["pcie_bandwidth_h2d"],
            gpu_peak_flops=data["gpu_peak_flops"],
            hidden_size=data["hidden_size"],
            num_attention_heads=data["num_attention_heads"],
            num_kv_heads=data.get("num_kv_heads", data["num_attention_heads"]),
            head_dim=data["head_dim"],
            ffn_dim=data["ffn_dim"],
            num_layers=data["num_layers"],
            dtype_bytes=data.get("dtype_bytes", 2),
            model_type=data.get("model_type", "opt"),
            attention_qkv_flops_coefficient=data.get(
                "attention_qkv_flops_coefficient", 6.0
            ),
            attention_output_flops_coefficient=data.get(
                "attention_output_flops_coefficient", 2.0
            ),
            # Preserve the historical planner formula for legacy profiles.
            # Newly generated profiles count both QK^T and score·V.
            attention_score_flops_coefficient=data.get(
                "attention_score_flops_coefficient", 2.0
            ),
            mlp_flops_coefficient=data.get("mlp_flops_coefficient", 4.0),
        )


@dataclass(frozen=True)
class TightLLMModelProfileSpec:
    """Normalized model architecture used by the microbenchmarks."""

    model_type: str
    hidden_size: int
    num_attention_heads: int
    num_kv_heads: int
    head_dim: int
    ffn_dim: int
    num_layers: int
    norm_eps: float
    attention_qkv_flops_coefficient: float
    attention_output_flops_coefficient: float
    attention_score_flops_coefficient: float
    mlp_flops_coefficient: float

    @property
    def uses_rms_norm(self) -> bool:
        return self.model_type == "llama"

    @property
    def uses_swiglu(self) -> bool:
        return self.model_type == "llama"


def resolve_model_profile_spec(config) -> TightLLMModelProfileSpec:
    """Resolve supported HuggingFace configs without changing the JSON schema.

    OPT keeps the legacy MHA + ReLU/two-projection benchmark. Llama uses
    RMSNorm, its configured MHA/GQA projection widths, and SwiGLU's
    gate/up/down projections.
    """

    model_type = str(getattr(config, "model_type", "")).lower()
    if model_type not in {"llama", "opt"}:
        raise ValueError(
            "TightLLM offline profiling currently supports only OPT and Llama; "
            f"got model_type={model_type!r}."
        )

    hidden_size = int(config.hidden_size)
    num_attention_heads = int(config.num_attention_heads)
    num_kv_heads = int(
        getattr(config, "num_key_value_heads", None) or num_attention_heads
    )
    head_dim = int(
        getattr(config, "head_dim", None)
        or hidden_size // num_attention_heads
    )
    num_layers = int(config.num_hidden_layers)

    if hidden_size <= 0 or num_attention_heads <= 0 or num_kv_heads <= 0:
        raise ValueError("Model hidden size and attention head counts must be > 0.")
    if head_dim <= 0 or num_attention_heads * head_dim != hidden_size:
        raise ValueError(
            "TightLLM profiling requires num_attention_heads * head_dim "
            f"to equal hidden_size; got {num_attention_heads} * {head_dim} "
            f"!= {hidden_size}."
        )
    if num_attention_heads % num_kv_heads != 0:
        raise ValueError(
            "num_attention_heads must be divisible by num_key_value_heads; "
            f"got {num_attention_heads} and {num_kv_heads}."
        )

    if model_type == "llama":
        ffn_dim = int(config.intermediate_size)
        hidden_act = str(getattr(config, "hidden_act", "silu")).lower()
        if hidden_act != "silu":
            raise ValueError(
                "Llama TightLLM profiling currently requires hidden_act='silu'; "
                f"got {hidden_act!r}."
            )
        norm_eps = float(getattr(config, "rms_norm_eps", 1e-6))
        mlp_flops_coefficient = 6.0
    else:
        ffn_dim = int(
            getattr(config, "ffn_dim", None)
            or getattr(config, "intermediate_size", 4 * hidden_size)
        )
        norm_eps = float(getattr(config, "layer_norm_eps", 1e-5))
        mlp_flops_coefficient = 4.0

    if ffn_dim <= 0 or num_layers <= 0 or norm_eps <= 0:
        raise ValueError("Model FFN size, layer count, and norm epsilon must be > 0.")

    kv_ratio = num_kv_heads / num_attention_heads
    # Q costs 2*H^2 FLOPs/token; K and V together cost
    # 4*H^2*(num_kv_heads/num_attention_heads). Standard output projection
    # costs another 2*H^2.
    attention_qkv_flops_coefficient = 2.0 + 4.0 * kv_ratio

    return TightLLMModelProfileSpec(
        model_type=model_type,
        hidden_size=hidden_size,
        num_attention_heads=num_attention_heads,
        num_kv_heads=num_kv_heads,
        head_dim=head_dim,
        ffn_dim=ffn_dim,
        num_layers=num_layers,
        norm_eps=norm_eps,
        attention_qkv_flops_coefficient=attention_qkv_flops_coefficient,
        attention_output_flops_coefficient=2.0,
        attention_score_flops_coefficient=4.0,
        mlp_flops_coefficient=mlp_flops_coefficient,
    )


